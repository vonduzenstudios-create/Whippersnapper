export const CHAR_W = 6;
export const CHAR_H = 8;

export function textWidth(s: string) {
  return s.length * CHAR_W - 1;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  s: string,
  x: number,
  y: number,
  color = '#e8dcc8',
  shadow: string | null = '#000000',
  align: 'left' | 'center' | 'right' = 'left',
) {
  s = s.toUpperCase();
  if (align === 'center') x -= Math.floor(textWidth(s) / 2);
  else if (align === 'right') x -= textWidth(s);
  x = Math.round(x);
  y = Math.round(y);
  if (shadow) drawRaw(ctx, s, x + 1, y + 1, shadow);
  drawRaw(ctx, s, x, y, color);
}

function drawRaw(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color: string) {
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const g = G[s[i]];
    if (!g) continue;
    for (let r = 0; r < 7; r++) {
      const row = g[r];
      if (!row) continue;
      for (let c = 0; c < 5; c++) if (row & (16 >> c)) ctx.fillRect(x + i * CHAR_W + c, y + r, 1, 1);
    }
  }
}

/** Big text: each font pixel drawn as an s x s block (used for titles). */
export function drawBigText(ctx: CanvasRenderingContext2D, s: string, cx: number, y: number, scale: number, color: string, shadow = '#000') {
  s = s.toUpperCase();
  const w = s.length * CHAR_W * scale - scale;
  const x0 = Math.round(cx - w / 2);
  for (const [col, off] of [[shadow, scale >> 1 || 1], [color, 0]] as [string, number][]) {
    ctx.fillStyle = col;
    for (let i = 0; i < s.length; i++) {
      const g = G[s[i]];
      if (!g) continue;
      for (let r = 0; r < 7; r++)
        for (let c = 0; c < 5; c++)
          if (g[r] & (16 >> c)) ctx.fillRect(x0 + (i * CHAR_W + c) * scale + off, y + r * scale + off, scale, scale);
    }
  }
}
